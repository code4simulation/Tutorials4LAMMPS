def get_ideal_gas_fe(temp, rho, mass_g_mol):
    # mass of one particle in kg
    m = (mass_g_mol / Na) * 1e-3
    beta = 1 / (kb * temp)
    # thermal wavelength Lambda in Angstrom
    # Lambda = sqrt(h^2 / (2*pi*m*kb*T))
    # h is Plank's constant. Using J s for internal calc.
    h_Js = const.h
    kb_JK = const.k
    Lambda_m = np.sqrt(h_Js**2 / (2 * np.pi * m * kb_JK * temp))
    Lambda_A = Lambda_m * 1e10
    
    # F_ideal = kBT * [ln(rho * Lambda^3) - 1]
    fe = kb * temp * (np.log(rho * (Lambda_A**3)) - 1)
    return fe

def press_uf(x, coef):
    return coef[0] * (x**3) + coef[1] * (x**2) + coef[2] * x + coef[3]

def fe_uf(x, coef, sum_spline, index):
    if x < 0.0025:
        return coef[0] * (x**2) / 2.0 + coef[1] * x
    elif x < 0.1:
        if x * 10000 % 25 == 0: return sum_spline[index - 1]
        x_0 = 0.0025 * int(x * 400)
    elif x < 1:
        if x * 1000 % 25 == 0: return sum_spline[index - 1]
        x_0 = 0.025 * int(x * 40)
    elif x < 4:
        if x * 100 % 10 == 0: return sum_spline[index - 1]
        x_0 = 0.1 * int(x * 10)
    else:
        return sum_spline[index]

    result = (
        sum_spline[index - 1]
        + coef[0] * (x**2.0 - x_0**2.0) / 2.0
        + coef[1] * (x - x_0)
        + (coef[2] - 1.0) * math.log(x / x_0)
        - coef[3] * (1.0 / x - 1.0 / x_0)
    )
    return result

